"""Full-wrap paperback cover for Amazon KDP (8.5 x 11 in, standard colour, white paper).

Spine width = page count x 0.002347 in (KDP, colour interiors); bleed 0.125 in on every edge.
Reads the page count of ../../kdp.pdf, draws the artwork of generar.py (seed 42) on the front,
writes kdp-cover.tex and compiles it with XeLaTeX. Run: python make_kdp_cover.py"""
import pathlib
import random
import re
import subprocess

import cairosvg
import generar

HERE = pathlib.Path(__file__).parent
BLEED, TRIM_W, TRIM_H, PER_PAGE = 0.125, 8.5, 11.0, 0.002347

pages = int(re.search(r"Pages:\s+(\d+)", subprocess.run(["pdfinfo", str(HERE / "../../kdp.pdf")],
                                                         capture_output=True, text=True).stdout).group(1))
pages += pages % 2                                   # KDP rounds up to an even page count
spine = pages * PER_PAGE
W, H = 2 * BLEED + 2 * TRIM_W + spine, 2 * BLEED + TRIM_H
front_w = TRIM_W + BLEED

# front artwork: the original design, cropped at the bottom to the proportions of the front panel
background, paths = generar.flow(random.Random(42))
vb_h = round(generar.W * H / front_w)
svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{front_w}in" height="{H}in" viewBox="0 0 {generar.W} {vb_h}">'
       f'<rect width="100%" height="100%" fill="{background}"/>' + "".join(paths) + "</svg>")
cairosvg.svg2pdf(bytestring=svg.encode(), write_to=str(HERE / "cover-front-kdp.pdf"))

# back: the bottom of the same artwork at 300 dpi, blended into the background colour (no transparency in the PDF)
import io
import numpy as np
from PIL import Image
BAND, DPI = 3.7, 300
png = cairosvg.svg2png(bytestring=svg.encode(), output_width=round(front_w * DPI), output_height=round(H * DPI))
art = np.asarray(Image.open(io.BytesIO(png)).convert("RGB")).astype(float)
band = art[-round(BAND * DPI):]
bg = np.array([int(background[k:k + 2], 16) for k in (1, 3, 5)], float)
y = np.linspace(0, 1, band.shape[0])[:, None, None]
alpha = 0.45 * np.clip(y / 0.45, 0, 1) ** 2                      # transparent at the top of the band
Image.fromarray((bg * (1 - alpha) + band * alpha).astype("uint8")).save(HERE / "back-art.png", dpi=(DPI, DPI))

x_spine, x_front = BLEED + TRIM_W, BLEED + TRIM_W + spine
top = H - BLEED                                      # top trim line
tex = rf"""% Generated by make_kdp_cover.py for {pages} pages: {W:.4f} x {H:.4f} in, spine {spine:.4f} in
\documentclass{{article}}
\usepackage[paperwidth={W:.4f}in,paperheight={H:.4f}in,margin=0pt]{{geometry}}
\usepackage{{fontspec,xcolor,graphicx,tikz}}
\setmainfont{{LibertinusSerif}}[Path=../../fonts/,Extension=.otf,UprightFont=*-Regular,ItalicFont=*-Italic,BoldFont=*-Semibold]
\setsansfont{{LibertinusSans}}[Path=../../fonts/,Extension=.otf,UprightFont=*-Regular,BoldFont=*-Bold]
\definecolor{{bg}}{{HTML}}{{091C30}}
\definecolor{{covertitle}}{{HTML}}{{F5F2E9}}
\definecolor{{coverauthors}}{{HTML}}{{85B3BC}}
\definecolor{{backtext}}{{HTML}}{{E3DED2}}
\pagestyle{{empty}}
\begin{{document}}
\null\begin{{tikzpicture}}[remember picture,overlay,x=1in,y=1in,inner sep=0pt,shift={{(current page.south west)}}]
  \fill[bg] (0,0) rectangle ({W:.4f},{H:.4f});
  % front
  \node[anchor=south west] at ({x_front:.4f},0) {{\includegraphics[width={front_w}in,height={H}in]{{cover-front-kdp.pdf}}}};
  \begin{{scope}}[x=1mm,y=1mm,shift={{({x_front:.4f}in,{top:.4f}in)}}]
    \node[anchor=base west,text=covertitle,font=\sffamily\bfseries\fontsize{{31}}{{37}}\selectfont] at (17,-21) {{Evaluation, Deployment}};
    \node[anchor=base west,text=covertitle,font=\sffamily\bfseries\fontsize{{31}}{{37}}\selectfont] at (17,-34.5) {{and Monitoring of Models}};
    \node[anchor=base west,text=coverauthors,font=\sffamily\fontsize{{13.5}}{{16}}\selectfont] at (17,-49.5) {{C\`esar Ferri, Carlos Monserrat, Yael Moros, F\'elix Mart\'i,}};
    \node[anchor=base west,text=coverauthors,font=\sffamily\fontsize{{13.5}}{{16}}\selectfont] at (17,-56.3) {{Daniel Romero-Alvarado and Fernando Mart\'inez-Plumed}};
  \end{{scope}}
  % spine, read from top to bottom
  \node[rotate=-90,anchor=center] at ({x_spine + spine / 2:.4f},{H / 2:.4f})
    {{{{\color{{covertitle}}\sffamily\bfseries\fontsize{{13}}{{15}}\selectfont Evaluation, Deployment and Monitoring of Models}}%
      \hspace{{0.45in}}{{\color{{coverauthors}}\sffamily\fontsize{{9.5}}{{11}}\selectfont Ferri \textperiodcentered{{}} Monserrat \textperiodcentered{{}} Moros \textperiodcentered{{}} Mart\'i \textperiodcentered{{}} Romero-Alvarado \textperiodcentered{{}} Mart\'inez-Plumed}}}};
  % back: the lower part of the artwork, faded into the background (back-art.png)
  \node[anchor=south west] at (0,0) {{\includegraphics[width={front_w}in,height={BAND}in]{{back-art.png}}}};
  % back
  \node[anchor=north west,text width=6.9in,align=left] at ({BLEED + 0.8:.4f},{top - 0.85:.4f}) {{%
    {{\color{{covertitle}}\sffamily\bfseries\fontsize{{21}}{{26}}\selectfont Evaluation, Deployment\\ and Monitoring of Models\par}}
    \vspace{{14pt}}{{\color{{coverauthors}}\rule{{1.2in}}{{1.2pt}}}}\par\vspace{{14pt}}
    {{\color{{backtext}}\fontsize{{12}}{{16.5}}\selectfont
    Training a model is the easy part. Deciding whether it is good enough\,---\,for whom, for what and for how long\,---\,is
    the hard part, and the subject of this book.\par\medskip
    It follows a model through the rest of its life: how to evaluate it honestly, with sound protocols, the right metrics
    and statistical comparisons; how to combine models with each other and with expert knowledge, and when a model should not predict at all; how to make models
    fair, explainable, secure and compliant with the European AI Act; how to automate data science, with and without
    language models; how to deploy models with APIs, pipelines and tests; and how to monitor them when the world changes,
    with drift detection, A/B tests and bandits.\par\medskip
    Every unit includes Python code that was run to produce the results shown, and exercises with solutions.\par\bigskip
    {{\color{{coverauthors}}\sffamily\fontsize{{10.5}}{{14}}\selectfont
    1\enspace Model evaluation\quad 2\enspace Hybrid models\quad 3\enspace Reliable models\quad 4\enspace Learning to learn\\
    5\enspace Deployment\quad 6\enspace Monitoring and updating\quad 7\enspace Applications\par}}
    \vspace{{22pt}}
    {{\sffamily\fontsize{{10.5}}{{14}}\selectfont C\`esar Ferri\enspace\textperiodcentered\enspace Carlos Monserrat\enspace\textperiodcentered\enspace
    Yael Moros\enspace\textperiodcentered\enspace F\'elix Mart\'i\enspace\textperiodcentered\enspace Daniel Romero-Alvarado\enspace\textperiodcentered\enspace Fernando Mart\'inez-Plumed\par}}}}}};
  % the barcode area at the bottom right of the back cover (2 x 1.2 in, 0.25 in from the trim) is left empty
\end{{tikzpicture}}
\end{{document}}
"""
(HERE / "kdp-cover.tex").write_text(tex)
for _ in range(2):                                    # overlay positions need two runs
    subprocess.run(["xelatex", "-interaction=nonstopmode", "kdp-cover.tex"], cwd=HERE, capture_output=True)
for ext in (".aux", ".log"):
    (HERE / f"kdp-cover{ext}").unlink(missing_ok=True)
print(f"kdp-cover.pdf: {pages} pages, spine {spine:.4f} in, full cover {W:.4f} x {H:.4f} in")
